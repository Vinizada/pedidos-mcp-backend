def synthetic_ean(sequence: int) -> str:
    """Gera código de teste EAN-13; não implica registro comercial GS1."""
    if not 1 <= sequence <= 999999:
        raise ValueError("A sequência deve estar entre 1 e 999999.")
    body = f"299000{sequence:06d}"
    weighted_sum = sum(int(digit) * (1 if i % 2 == 0 else 3) for i, digit in enumerate(body))
    return body + str((-weighted_sum) % 10)


