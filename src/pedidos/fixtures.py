def catalog_records() -> list[ProductRecord]:
    """Retorna 100 registros independentes, em ordem estável de SKU.

    MER-099 está sem estoque; MER-100 está inativo. Cada quantidade é medida
    em unidades da embalagem cadastrada (UN), nunca em gramas ou mililitros.
    """
    records: list[ProductRecord] = []
    for number, (nome, marca, categoria, embalagem, aliases, cents) in enumerate(_CATALOG, 1):
        records.append(
            {
                "sku": f"MER-{number:03d}",
                "ean": synthetic_ean(number),
                "nome": nome,
                "marca": marca,
                "categoria": categoria,
                "unidade": "UN",
                "embalagem": embalagem,
                "descricao_busca": f"{nome}; marca {marca}; {categoria}; {embalagem}; {aliases}",
                "preco": f"{cents // 100}.{cents % 100:02d}",
                "quantidade": 0 if number == 99 else 50 + (number * 17) % 151,
                "ativo": number != 100,
            }
        )
    return records


